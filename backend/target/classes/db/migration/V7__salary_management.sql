-- =====================================================================
-- V7__salary_management.sql
--
-- Tables for the HR/Admin Salary Management module: a versioned pay
-- definition per employee (salary_structure), monthly payroll batches
-- (payroll_run), and each employee's frozen payslip line within a batch
-- (payroll_item). Nothing in the shared HaodaAsset schema covers
-- compensation, so - per the "only create new tables when absolutely
-- required" rule already followed in V2 - these three are new.
--
-- Column shapes match HaodaOne's JPA entities exactly (SalaryStructure,
-- PayrollRun, PayrollItem, and the SalaryComponents embeddable shared by
-- the first and third) since spring.jpa.hibernate.ddl-auto=validate does
-- not create anything itself.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.salary_structure (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             bigint NOT NULL DEFAULT 0,
    created_at          timestamp(6) without time zone NOT NULL DEFAULT now(),
    updated_at          timestamp(6) without time zone NOT NULL DEFAULT now(),
    created_by          character varying(100),
    updated_by          character varying(100),
    deleted             boolean NOT NULL DEFAULT false,
    deleted_at          timestamp(6) without time zone,
    employee_id         bigint NOT NULL REFERENCES public.employee(id),
    effective_from      date NOT NULL,
    active              boolean NOT NULL DEFAULT true,
    basic_salary        numeric(14,2) NOT NULL DEFAULT 0,
    hra                 numeric(14,2) NOT NULL DEFAULT 0,
    special_allowance   numeric(14,2) NOT NULL DEFAULT 0,
    medical_allowance   numeric(14,2) NOT NULL DEFAULT 0,
    travel_allowance    numeric(14,2) NOT NULL DEFAULT 0,
    bonus               numeric(14,2) NOT NULL DEFAULT 0,
    incentives          numeric(14,2) NOT NULL DEFAULT 0,
    overtime            numeric(14,2) NOT NULL DEFAULT 0,
    pf                  numeric(14,2) NOT NULL DEFAULT 0,
    esi                 numeric(14,2) NOT NULL DEFAULT 0,
    professional_tax    numeric(14,2) NOT NULL DEFAULT 0,
    tds                 numeric(14,2) NOT NULL DEFAULT 0,
    other_deductions    numeric(14,2) NOT NULL DEFAULT 0,
    gross_salary        numeric(14,2) NOT NULL DEFAULT 0,
    total_deductions    numeric(14,2) NOT NULL DEFAULT 0,
    net_salary          numeric(14,2) NOT NULL DEFAULT 0,
    notes               character varying(1000)
);
CREATE INDEX IF NOT EXISTS idx_salary_structure_employee_id ON public.salary_structure (employee_id);

-- Exactly one active structure per employee at a time - enforced here, not just in SalaryStructureService.
CREATE UNIQUE INDEX IF NOT EXISTS uq_salary_structure_one_active_per_employee
    ON public.salary_structure (employee_id)
    WHERE active = true AND deleted = false;

CREATE TABLE IF NOT EXISTS public.payroll_run (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             bigint NOT NULL DEFAULT 0,
    created_at          timestamp(6) without time zone NOT NULL DEFAULT now(),
    updated_at          timestamp(6) without time zone NOT NULL DEFAULT now(),
    created_by          character varying(100),
    updated_by          character varying(100),
    deleted             boolean NOT NULL DEFAULT false,
    deleted_at          timestamp(6) without time zone,
    period_month        integer NOT NULL,
    period_year         integer NOT NULL,
    status              character varying(20) NOT NULL DEFAULT 'DRAFT',
    pay_date            date,
    processed_at        timestamp(6) without time zone,
    total_employees     integer NOT NULL DEFAULT 0,
    total_gross         numeric(16,2) NOT NULL DEFAULT 0,
    total_deductions    numeric(16,2) NOT NULL DEFAULT 0,
    total_net           numeric(16,2) NOT NULL DEFAULT 0,
    remarks             character varying(1000)
);

-- One run per calendar period - a second DRAFT for the same month would double-pay employees if both were ever processed.
CREATE UNIQUE INDEX IF NOT EXISTS uq_payroll_run_period
    ON public.payroll_run (period_year, period_month)
    WHERE deleted = false;

CREATE TABLE IF NOT EXISTS public.payroll_item (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             bigint NOT NULL DEFAULT 0,
    created_at          timestamp(6) without time zone NOT NULL DEFAULT now(),
    updated_at          timestamp(6) without time zone NOT NULL DEFAULT now(),
    created_by          character varying(100),
    updated_by          character varying(100),
    deleted             boolean NOT NULL DEFAULT false,
    deleted_at          timestamp(6) without time zone,
    payroll_run_id      bigint NOT NULL REFERENCES public.payroll_run(id),
    employee_id         bigint NOT NULL REFERENCES public.employee(id),
    salary_structure_id bigint REFERENCES public.salary_structure(id),
    basic_salary        numeric(14,2) NOT NULL DEFAULT 0,
    hra                 numeric(14,2) NOT NULL DEFAULT 0,
    special_allowance   numeric(14,2) NOT NULL DEFAULT 0,
    medical_allowance   numeric(14,2) NOT NULL DEFAULT 0,
    travel_allowance    numeric(14,2) NOT NULL DEFAULT 0,
    bonus               numeric(14,2) NOT NULL DEFAULT 0,
    incentives          numeric(14,2) NOT NULL DEFAULT 0,
    overtime            numeric(14,2) NOT NULL DEFAULT 0,
    pf                  numeric(14,2) NOT NULL DEFAULT 0,
    esi                 numeric(14,2) NOT NULL DEFAULT 0,
    professional_tax    numeric(14,2) NOT NULL DEFAULT 0,
    tds                 numeric(14,2) NOT NULL DEFAULT 0,
    other_deductions    numeric(14,2) NOT NULL DEFAULT 0,
    gross_salary        numeric(14,2) NOT NULL DEFAULT 0,
    total_deductions    numeric(14,2) NOT NULL DEFAULT 0,
    net_salary          numeric(14,2) NOT NULL DEFAULT 0,
    status              character varying(20) NOT NULL DEFAULT 'PENDING',
    payment_date        date,
    remarks             character varying(500)
);
CREATE INDEX IF NOT EXISTS idx_payroll_item_payroll_run_id ON public.payroll_item (payroll_run_id);
CREATE INDEX IF NOT EXISTS idx_payroll_item_employee_id ON public.payroll_item (employee_id);

-- One line per employee per run.
CREATE UNIQUE INDEX IF NOT EXISTS uq_payroll_item_run_employee
    ON public.payroll_item (payroll_run_id, employee_id)
    WHERE deleted = false;
