-- =====================================================================
-- V9__employee_document_expiry_tracking.sql
--
-- Backs the new Document Expiry Reminders feature (Phase 8). Nothing in
-- the HaodaAsset shared schema tracks document expiry, so - per the same
-- "only create new tables when absolutely required for new HRMS modules"
-- rule V2 followed for Goal/PerformanceReview/JobOpening/Candidate/
-- Interview - this is a single new table. Nothing existing is touched.
--
-- Deliberately metadata-only (type, number, dates, notes) - no file
-- storage column. Attaching actual scanned documents is a real follow-up
-- that would need S3 wiring like resume/offer-letter storage already
-- has, not included here; see EmployeeDocument.java.
--
-- Column shape matches EmployeeDocument.java exactly, same as every
-- other table added since spring.jpa.hibernate.ddl-auto=validate stopped
-- auto-creating anything.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.employee_document (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         bigint NOT NULL DEFAULT 0,
    created_at      timestamp(6) without time zone NOT NULL DEFAULT now(),
    updated_at      timestamp(6) without time zone NOT NULL DEFAULT now(),
    created_by      character varying(100),
    updated_by      character varying(100),
    deleted         boolean NOT NULL DEFAULT false,
    deleted_at      timestamp(6) without time zone,
    employee_id     bigint NOT NULL REFERENCES public.employee(id),
    document_type   character varying(40) NOT NULL,
    document_number character varying(100),
    issue_date      date,
    expiry_date     date NOT NULL,
    notes           character varying(500)
);
CREATE INDEX IF NOT EXISTS idx_employee_document_employee_id ON public.employee_document (employee_id);

-- Powers the "expiring soon" query (Dashboard widget + Settings list) -
-- without this, that query does a full table scan on expiry_date every
-- time it runs.
CREATE INDEX IF NOT EXISTS idx_employee_document_expiry_date ON public.employee_document (expiry_date);
